import { cp, mkdir, readFile, writeFile, rm, lstat } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

// npm ci restores the exact upstream bytes (including integrity checks).
// Keep generated vendor assets committed for static, build-free hosting too.
const manifest = JSON.parse(await readFile('package.json', 'utf8'));
for (const name of ['monaco-editor', 'jszip']) {
  const installed = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
  if (installed.version !== manifest.devDependencies[name]) {
    throw new Error(`${name}: run npm ci to restore the pinned runtime dependency`);
  }
}
const monaco = manifest.devDependencies['monaco-editor'];
const vendorRoot = path.resolve('assets/vendor/monaco-editor');
const destination = path.resolve(vendorRoot, monaco);
if (!/^\d+\.\d+\.\d+$/.test(monaco) || path.dirname(destination) !== vendorRoot) throw Error('Invalid Monaco output path');
const previous = await lstat(destination).catch(error => { if (error.code !== 'ENOENT') throw error; });
if (previous?.isSymbolicLink()) throw Error('Linked Monaco output is not supported');
await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
const workers = {
  'editor.worker': 'node_modules/monaco-editor/esm/vs/editor/editor.worker.js',
  ...Object.fromEntries(['html', 'css', 'json', 'typescript'].map(language => [
    `${language === 'typescript' ? 'ts' : language}.worker`,
    `node_modules/monaco-editor/esm/vs/languages/features/${language}/${language === 'typescript' ? 'ts' : language}.worker.js`
  ]))
};
const options = { bundle: true, minify: true, format: 'iife', target: 'es2020',
  outdir: `${destination}/browser`, loader: { '.ttf': 'file' }, legalComments: 'eof' };
await build({ ...options, entryPoints: { 'editor.main': 'src/editor/monaco-entry.js' } });
const workerBuild = await build({ ...options, entryPoints: workers, write: false });
for (const file of workerBuild.outputFiles) {
  const name = path.basename(file.path, '.worker.js');
  // The same artifact is a normal worker over HTTP, or a source loader for
  // Blob workers when the editor was opened directly from disk.
  await writeFile(file.path, `(()=>{function run(){\n${file.text}\nglobalThis.postMessage({type:"html-viewer-worker-ready"});\n}\n` +
    `if(typeof document==="undefined")run();else(globalThis.__htmlViewerWorkerSources??={})[${JSON.stringify(name)}]=run.toString();})();\n`);
}
await cp('node_modules/monaco-editor/LICENSE', `${destination}/LICENSE.txt`);

const source = await readFile('node_modules/jszip/dist/jszip.min.js', 'utf8');
await writeFile('vendor/jszip.min.js', source);
await cp('node_modules/jszip/LICENSE.markdown', 'assets/licenses/JSZip.txt');
// Keep ZIP independent of module loaders embedded by other scripts.
await writeFile('jszip.min.js',
  '/* Generated by build-vendor.mjs from the pinned JSZip npm package. */\n' +
  '(function(define,module,exports){\n' + source.trim() + '\n}).call(globalThis);\n');
console.log(`Built local Monaco ${monaco} and JSZip ${manifest.devDependencies.jszip}.`);
